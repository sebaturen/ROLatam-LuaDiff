function GetInheritTbl(in_Job)
	local tblInherit = {}
	table.insert(tblInherit, in_Job)
	local tmpJob = in_Job
	while nil ~= JOB_INHERIT_TREE[tmpJob] do
		for idx, Job in ipairs(JOB_INHERIT_TREE[tmpJob]) do
			table.insert(tblInherit, Job)
			tmpJob = Job
		end
	end
	return tblInherit
end
